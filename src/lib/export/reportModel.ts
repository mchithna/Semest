export function disclaimer(issuedOn: string) {
  return `Self-reported, generated by Semest on ${issuedOn}. Not an official transcript.`
}

export function formatCredits(value: number): string {
  const rounded = Math.round(value * 10) / 10
  return Number.isInteger(rounded) ? String(rounded) : rounded.toFixed(1)
}

export function reportFileName(studentName: string, degreeTitle: string, extension: 'pdf' | 'png') {
  const tail = extension === 'png' ? 'card' : 'transcript'
  const slug = [studentName, degreeTitle, tail]
    .join(' ')
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 80)
  return `${slug || tail}.${extension}`
}

function pointsFor(grade: string, scale: GradeRow[]): number | null {
  const row = scale.find((item) => item.grade.trim().toUpperCase() === grade.trim().toUpperCase())
  if (!row || !Number.isFinite(Number(row.points))) return null
  return Number(row.points)
}

function moduleCode(name: string, index: number): string {
  const match = name.trim().match(/^([A-Za-z]{2,}\s?\d{2,}[A-Za-z]?)\b/)
  return match ? match[1].replace(/\s+/g, '').toUpperCase() : String(index + 1).padStart(2, '0')
}

function moduleTitle(name: string, code: string): string {
  const trimmed = name.trim()
  if (code.length > 2 && trimmed.toUpperCase().replace(/\s+/g, '').startsWith(code)) {
    const rest = trimmed.replace(/^[\sA-Za-z0-9]*?\d+[A-Za-z]?/, '').replace(/^[\s\-–:]+/, '')
    return rest || trimmed
  }
  return trimmed || 'Untitled module'
}

function className(score: number, graded: boolean, track: BandTrack): string | null {
  const sentence = standingSentence(score, graded, track)
  if (!sentence) return null
  return sentence.replace(/, by \d+\.\d+\.$/, '')
}

export type PagePlan = {
  /** y where the first page's semester list starts, and where later pages start, in pt */
  firstStart: number
  laterStart: number
  /** y a block may not cross, in pt */
  limit: number
}

export function paginate(
  semesters: ReportSemester[],
  plan: PagePlan,
  blockHeight: (semester: ReportSemester) => number,
): ReportPage[] {
  const pages: ReportPage[] = []
  let current: string[] = []
  let used = plan.firstStart

  const flush = () => {
    pages.push({ index: pages.length, semesterIds: current, showIntro: pages.length === 0 })
    current = []
    used = plan.laterStart
  }

  for (const semester of semesters) {
    const height = blockHeight(semester)
    if (current.length > 0 && used + height > plan.limit) flush()
    current.push(semester.id)
    used += height
  }

  if (current.length > 0 || pages.length === 0) {
    pages.push({ index: pages.length, semesterIds: current, showIntro: pages.length === 0 })
  }
  return pages
}
export function buildReport(input: BuildReportInput): ReportModel {
  const scale = input.degree.grade_scale?.grades ?? []
  const track = bandsForScale(scale, classBandsOf(input.degree.grade_scale))
  const hasClassBands = track.bands.some((band) => band.tone !== 'plain')
  const show = { ...input.toggles }
  if (!hasClassBands) show.classificationRuler = false
  const includeInProgress = show.inProgressSemesters
  const keptIds = new Set(
    withoutReplacedAttempts(input.semesters.flatMap((semester) => semester.modules)).map((mod) => mod.id),
  )

  const semesters = [...input.semesters].sort(compareSemesters).flatMap((semester) => {
    const modules = semester.modules
      .filter((mod) => keptIds.has(mod.id))
      .filter((mod) => includeInProgress || !isUngradedGrade(mod.grade))
      .map((mod, index): ReportModule => {
        const inProgress = isUngradedGrade(mod.grade) || pointsFor(mod.grade, scale) == null
        const code = moduleCode(mod.name, index)
        return {
          id: mod.id,
          code,
          name: moduleTitle(mod.name, code),
          credits: toCredits(mod.credits),
          grade: inProgress ? 'In progress' : mod.grade,
          points: inProgress ? null : pointsFor(mod.grade, scale),
          inProgress,
        }
      })
    if (modules.length === 0) return []
    const gradedModules = semester.modules.filter(
      (mod) => keptIds.has(mod.id) && !isUngradedGrade(mod.grade) && pointsFor(mod.grade, scale) != null,
    )
    const graded = gradedModules.length > 0
    return [
      {
        id: semester.id,
        title: semester.term && !semester.title.toLowerCase().includes(semester.term.toLowerCase())
          ? `${semester.title}, ${semester.term}`
          : semester.title,
        credits: modules.reduce((sum, mod) => sum + mod.credits, 0),
        gpa: graded ? computeScore(gradedModules, scale) : null,
        graded,
        className: graded ? className(computeScore(gradedModules, scale), true, track) : null,
        modules,
      },
    ]
  })

  const gradedRows = semesters.flatMap((semester) =>
    semester.modules.filter((mod) => !mod.inProgress && mod.points != null),
  )
  const gradedCredits = gradedRows.reduce((sum, mod) => sum + mod.credits, 0)
  const cgpa =
    gradedCredits > 0
      ? Number((gradedRows.reduce((sum, mod) => sum + (mod.points ?? 0) * mod.credits, 0) / gradedCredits).toFixed(4))
      : null
  const gradedSemesters = semesters.filter((semester) => semester.graded && semester.gpa != null)
  const best = gradedSemesters.reduce<ReportSemester | null>(
    (winner, semester) => (winner == null || (semester.gpa ?? 0) > (winner.gpa ?? 0) ? semester : winner),
    null,
  )
  const issued = input.issuedOn ?? new Date()
  const standing = cgpa != null ? standingSentence(cgpa, true, track) : null
  const next = cgpa != null ? nextBandSentence(cgpa, track) : null
  const nextBand =
    cgpa == null
      ? null
      : track.bands.find((item) => item.tone !== 'plain' && item.min > cgpa + 0.0005) ?? null
  const distanceToNext =
    cgpa != null && nextBand ? (Math.round((nextBand.min - cgpa) * 100) / 100).toFixed(2) : null
  const nextClass = next?.match(/reaches (.+)\.$/)?.[1] ?? null

  const gradeList = scale.map((row) => `${row.grade} ${formatGpa(Number(row.points))}`).join(', ')
  const cuts = track.bands
    .filter((item) => item.tone !== 'plain')
    .map((item) => `${item.label} ${formatGpa(item.min)}`)
    .join(', ')
  const scaleNote = scale.length
    ? `Grade scale: ${gradeList}.${cuts ? ` Classification: ${cuts}.` : ''}`
    : 'No grade scale is attached to this degree.'
  const gradeScaleList = scale.length ? gradeList : 'No grade scale is attached to this degree.'
  const classificationList = cuts || 'This grade scale has no classification bands.'

  const keyH = show.gradeScale ? keyHeight(input.paper, gradeScaleList, classificationList) : 0
  const limit = contentBottom(input.paper, keyH)
  const nameColumn = rulerNameColumn(input.paper)
  const pages =
    input.theme === 'social'
      ? [{ index: 0, semesterIds: semesters.map((semester) => semester.id), showIntro: true }]
      : input.theme === 'ruler'
        ? paginate(
            semesters,
            {
              firstStart: rulerIntroBottom({
                paper: input.paper,
                summary: show.summaryFigures,
                ruler: show.classificationRuler && hasClassBands,
                fallbackNote: show.classificationRuler && !hasClassBands,
                target: show.targetGoal && input.targetCgpa != null,
              }),
              laterStart: rulerRunningBottom(),
              limit,
            },
            (semester) => rulerRowHeight(semester.title, nameColumn),
          )
        : paginate(
            semesters,
            {
              firstStart: formalIntroBottom(show),
              laterStart: MARGIN + FORMAL.running + 8,
              limit,
            },
            (semester) => formalBlockHeight(semester.modules.length),
          )
  return {
    theme: input.theme,
    title: input.title.trim() || `${input.degree.title} Academic Transcript`,
    institution: input.degree.institution?.trim() || '',
    degreeTitle: input.degree.title,
    startedYear: input.degree.started_year,
    studentName: input.studentName.trim(),
    studentId: input.studentId.trim(),
    issuedOn: issued.toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' }),
    cgpa,
    earnedCredits: gradedCredits,
    totalCredits: input.semesters
      .flatMap((semester) => semester.modules)
      .filter((mod) => keptIds.has(mod.id))
      .reduce((sum, mod) => sum + toCredits(mod.credits), 0),
    bestSemesterGpa: best?.gpa ?? null,
    classification: cgpa != null ? className(cgpa, true, track) : null,
    standing,
    nextBand: next,
    nextClass,
    distanceToNext,
    gradedSemesterCount: gradedSemesters.length,
    scaleNote,
    gradeScaleList,
    classificationList,
    keyHeight: keyH,
    track,
    hasClassBands,
    semesters,
    show,
    paper: input.paper,
    aspect: input.aspect,
    targetCgpa: show.targetGoal ? input.targetCgpa ?? null : null,
    pages,
    hideExactGpa: input.theme === 'social' && show.hideExactGpa,
  }
}

/** "CS 26', NIBM" for the top right of a document. */
export function degreeLine(model: ReportModel) {
  return [model.degreeTitle, model.show.degreeInstitution ? model.institution : ''].filter(Boolean).join(', ')
}

/** "Alex Morgan, CS26-0142". Empty unless the student details toggle is on and there is something to show. */
export function studentLine(model: ReportModel) {
  if (!model.show.studentDetails) return ''
  return [model.studentName, model.studentId].filter(Boolean).join(', ')
}

export function pageCountLabel(model: ReportModel) {
  const count = model.pages.length
  const noun = count === 1 ? 'page' : 'pages'
  if (model.theme === 'social') return model.aspect
  return `Prints on ${count} ${noun}`
}

export function outputExtension(theme: ThemeId) {
  return THEMES[theme].output === 'png' ? 'png' : 'pdf'
}
